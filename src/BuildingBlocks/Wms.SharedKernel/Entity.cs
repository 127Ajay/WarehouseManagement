namespace Wms.SharedKernel;

/// <summary>Something that happened inside a module's domain.</summary>
public interface IDomainEvent;

/// <summary>Entity with identity. Equality is by Id only.</summary>
public abstract class Entity<TId> : IEquatable<Entity<TId>>
    where TId : notnull
{
    protected Entity(TId id) => Id = id;

    public TId Id { get; private init; }

    public bool Equals(Entity<TId>? other) =>
        other is not null && other.GetType() == GetType() && EqualityComparer<TId>.Default.Equals(Id, other.Id);

    public override bool Equals(object? obj) => obj is Entity<TId> other && Equals(other);

    public override int GetHashCode() => HashCode.Combine(GetType(), Id);
}

/// <summary>Consistency boundary. Collects domain events raised during a command.</summary>
public abstract class AggregateRoot<TId> : Entity<TId>
    where TId : notnull
{
    private readonly List<IDomainEvent> _domainEvents = [];

    protected AggregateRoot(TId id)
        : base(id)
    {
    }

    public IReadOnlyList<IDomainEvent> DomainEvents => _domainEvents;

    protected void Raise(IDomainEvent domainEvent) => _domainEvents.Add(domainEvent);

    public void ClearDomainEvents() => _domainEvents.Clear();
}

/// <summary>
/// Marks data owned by one tenant. The ORM filters and stamps TenantId automatically,
/// and PostgreSQL row-level security enforces it again in the database.
/// </summary>
public interface ITenantOwned
{
    Guid TenantId { get; set; }
}
